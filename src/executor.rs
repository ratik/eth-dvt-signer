pub struct ExportEntry {
    pub chain: Option<ChainIdentity>,
    pub exported: Exported,
}

/// What the committed state says about a duty right now (nothing is recorded).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DutyCheck {
    /// The validator, if the key is one.
    pub validator: Option<ValidatorEntry>,
    pub signing_root: Root,
    /// `Accepted` means: not authorized yet, consensus may authorize it.
    pub decision: Decision,
    /// The block that authorized it, when it already is.
    pub height: Option<u64>,
    /// Its signing root is approved (P0.2): a keyholder signs an exit or a deposit only then.
    pub approved: bool,
    /// For a duty the fee-recipient policy binds (a builder registration, Gloas proposer
    /// preferences or envelope), the registration policy in force (none: none is set).
    pub policy: Option<RegistrationPolicy>,
}

/// The node's mempool holds [MAX_PENDING_REGISTRATIONS] registrations already: a new one is not
/// submitted (retry later).
#[derive(Clone, Copy, Debug, PartialEq, Eq, thiserror::Error)]
#[error("too many builder registrations are waiting for consensus: retry later")]
pub struct Overloaded;

/// Why a duty was not submitted.
#[derive(Debug, thiserror::Error)]
pub enum SubmitError {
    #[error(transparent)]
    Stopped(#[from] Stopped),
    #[error(transparent)]
    Overloaded(#[from] Overloaded),
}

