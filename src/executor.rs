/// Why a node stops on its own: its consensus epoch ended with the last block it applied, or the
/// anchor shows its network was rolled back.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Stop {
    /// The block at `height` ended the epoch with a reconfiguration: the node restarts in `epoch`.
    Reconfigured { epoch: u64, height: u64 },
    /// The epoch was closed at `height` (`--close-epoch-at`) by a block without a
    /// reconfiguration: the node restarts in the same epoch without the closing height.
    Closed { height: u64 },
    /// The anchor's records show this node's chain is not the one that was signed under, or that
    /// another process writes as it (`anchor`): exit status 77, an operator's matter.
    RolledBack { height: u64 },
}

/// A client waiting for its transaction.
enum Waiter {
    Sign(oneshot::Sender<Receipt>),
    Start(oneshot::Sender<StartReceipt>),
    Duty(oneshot::Sender<Result<DutyReceipt, Overloaded>>),
    Activate(oneshot::Sender<ActivationReceipt>),
    ActivateBatch(oneshot::Sender<BatchActivationReceipt>),
    Register(oneshot::Sender<RegisterReceipt>),
    RegisterBatch(oneshot::Sender<BatchRegisterReceipt>),
    History(oneshot::Sender<HistoryReceipt>),
    Reshare(oneshot::Sender<ReshareReceipt>),
    Generation(oneshot::Sender<GenerationReceipt>),
    Abort(oneshot::Sender<AbortReceipt>),
}

impl Waiter {
    /// Its client stopped waiting (it gave up, or its request ended).
    fn is_closed(&self) -> bool {
        match self {
            Self::Sign(sender) => sender.is_closed(),
            Self::Start(sender) => sender.is_closed(),
            Self::Duty(sender) => sender.is_closed(),
            Self::Activate(sender) => sender.is_closed(),
            Self::ActivateBatch(sender) => sender.is_closed(),
            Self::Register(sender) => sender.is_closed(),
            Self::RegisterBatch(sender) => sender.is_closed(),
            Self::History(sender) => sender.is_closed(),
            Self::Reshare(sender) => sender.is_closed(),
            Self::Generation(sender) => sender.is_closed(),
            Self::Abort(sender) => sender.is_closed(),
        }
    }
}

/// The rounds of each validator key's completed reshares.
type ReshareRounds = HashMap<ValidatorKey, Vec<u64>>;

pub struct Executor<E: CryptoRng + Spawner + Context, S: Sender> {
    context: ContextCell<E>,
    store: Store<E>,
    mempool: Mempool,
    executed: Arc<AtomicU64>,
    /// The applied height and administrative nonce, for the application's checks.
    committed: Committed,
    /// Highest finalized height marshal knows of.
    tip: Arc<AtomicU64>,
    /// When this process last applied a new block.
    last_applied: Option<SystemTime>,
    /// Gossips locally submitted transactions so whichever node leads next can include them.
    gossip: S,
    mailbox: mpsc::UnboundedReceiver<Message>,
    /// Clients waiting for their transaction, by transaction id.
    waiters: HashMap<u64, Waiter>,
    /// Prunes finalized history outside the retention window.
    marshal: Marshal<Scheme, Standard<Block>>,
    retention: Retention,
    /// This node's DKG actor, told about every finalized block and ceremony change.
    dkg: mpsc::UnboundedSender<dkg::actor::Message>,
    /// Transactions this node submitted that no finalized block contains yet, if it is a follower
    /// (gossiped again until one does, [REGOSSIP_BLOCKS]); `None` on a voter.
    unfinalized: Option<HashMap<Digest, Transaction>>,
    /// The height the epoch was closed at (`--close-epoch-at`), if any.
    close: Option<u64>,
    /// Set, once, when the epoch ended with the last block applied; the executor then stops.
    stopped: Arc<OnceLock<Stop>>,
    /// The anchor's records read at start, compared with this node's chain as it applies blocks
    /// (`anchor`), until confirmed.
    anchor: Option<crate::anchor::Watch>,
    /// The rounds of each validator key's completed reshares, at the state height it was built
    /// at (`reshare_rounds`): a key's generation without a walk over every ceremony.
    reshares: RefCell<(Option<u64>, ReshareRounds)>,
}

impl<E: CryptoRng + Spawner + Context, S: Sender> Executor<E, S> {
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        context: E,
        store: Store<E>,
        mempool: Mempool,
        executed: Arc<AtomicU64>,
        committed: Committed,
        tip: Arc<AtomicU64>,
        gossip: S,
        marshal: Marshal<Scheme, Standard<Block>>,
        retention: Retention,
        dkg: mpsc::UnboundedSender<dkg::actor::Message>,
        follower: bool,
        close: Option<u64>,
        stopped: Arc<OnceLock<Stop>>,
    ) -> (Self, mpsc::UnboundedSender<Message>, Client) {
        executed.store(store.height(), Ordering::Release);
        committed.set(
            store.height(),
            store.admin().nonce,
            store.registration_policy().cloned(),
        );
        let (sender, mailbox) = mpsc::unbounded_channel();
        let executor = Self {
            context: ContextCell::new(context),
            store,
            mempool,
            executed,
            committed,
            tip,
            last_applied: None,
            gossip,
            mailbox,
            waiters: HashMap::new(),
            marshal,
            retention,
            dkg,
            unfinalized: follower.then(HashMap::new),
            close,
            stopped,
            anchor: None,
            reshares: RefCell::default(),
        };
        let client = Client {
            sender: sender.clone(),
        };
        (executor, sender, client)
    }

    /// Compare this node's chain with the anchor's records as blocks are applied.
    pub fn with_anchor(mut self, watch: Option<crate::anchor::Watch>) -> Self {
        self.anchor = watch;
        self
    }

    pub fn start(mut self) -> Handle<()> {
        spawn_cell!(self.context, self.run())
    }

    async fn run(mut self) {
        // Finalized blocks a test hook holds back (always empty in normal builds).
        let mut held: VecDeque<(Arc<Block>, Exact)> = VecDeque::new();
        loop {
            while !held.is_empty() && !hooks::holding() {
                let (block, ack) = held.pop_front().expect("not empty");
                self.execute(&block).await;
                ack.acknowledge();
                if self.stopped.get().is_some() {
                    return;
                }
            }
            let next = if held.is_empty() {
                Some(self.mailbox.recv().await)
            } else {
                select! {
                    message = self.mailbox.recv() => { Some(message) },
                    _ = self.context.sleep(HOLD_POLL) => { None },
                }
            };
            let Some(next) = next else { continue };
            let Some(message) = next else { return };
            match message {
                Message::Halt { reason } => {
                    error!(%reason, "stopping");
                    let _ = self.stopped.set(Stop::RolledBack {
                        height: self.store.height(),
                    });
                    return;
                }
                Message::Submit { request, response } => {
                    let ceremony = request.ceremony.clone();
                    let (nonce, payload_hash) = (request.nonce, request.payload_hash);
                    let id = self.submit(Command::Sign(request));
                    info!(
                        id,
                        %ceremony,
                        nonce,
                        payload_hash = %format_hash(&payload_hash),
                        "submitted signing authorization"
                    );
                    self.waiters.insert(id, Waiter::Sign(response));
                }
                Message::StartCeremony { config, response } => {
                    let ceremony = config.id.clone();
                    let id = self.submit(Command::StartCeremony(config));
                    info!(id, %ceremony, "received ceremony start");
                    self.waiters.insert(id, Waiter::Start(response));
                }
                Message::StartValidatorCeremony { config, response } => {
                    let ceremony = config.id.clone();
                    let id = self.submit(Command::StartValidatorCeremony(config));
                    info!(id, %ceremony, "received validator ceremony start");
                    self.waiters.insert(id, Waiter::Start(response));
                }
                Message::ActivateValidator {
                    validator,
                    chain,
                    endorsement,
                    response,
                } => {
                    let id = self.submit(endorse(
                        Command::ActivateValidator { validator, chain },
                        endorsement,
                    ));
                    info!(
                        id,
                        validator = %format_validator(&validator),
                        genesis_validators_root = %format_root(&chain.genesis_validators_root),
                        "submitted validator activation"
                    );
                    self.waiters.insert(id, Waiter::Activate(response));
                }
                Message::RegisterImport {
                    manifest,
                    endorsement,
                    response,
                } => {
                    let ceremony = manifest.ceremony.clone();
                    let validator = format_validator(&manifest.validator);
                    let id =
                        self.submit(endorse(Command::RegisterImportedKey(manifest), endorsement));
                    info!(id, %ceremony, %validator, "submitted imported key registration");
                    self.waiters.insert(id, Waiter::Register(response));
                }
                Message::RegisterImportBatch {
                    batch,
                    endorsement,
                    response,
                } => {
                    let keys = batch.manifests.len();
                    let id =
                        self.submit(endorse(Command::RegisterImportedKeys(batch), endorsement));
                    info!(id, keys, "submitted batch of imported key registrations");
                    self.waiters.insert(id, Waiter::RegisterBatch(response));
                }
                Message::SubmitReady { ack } => {
                    let round = ack.round;
                    let id = self.submit(Command::ShareReady(ack));
                    info!(id, round, "submitted share acknowledgement");
                }
                Message::StartResharing {
                    validator,
                    ceremony,
                    membership,
                    endorsement,
                    response,
                } => {
                    let id = self.submit(endorse(
                        Command::StartResharing {
                            validator,
                            ceremony: ceremony.clone(),
                            membership,
                        },
                        endorsement,
                    ));
                    info!(id, %ceremony, validator = %format_validator(&validator), "submitted reshare start");
                    self.waiters.insert(id, Waiter::Reshare(response));
                }
                Message::ActivateGeneration {
                    validator,
                    round,
                    response,
                } => {
                    let id = self.submit(Command::ActivateGeneration { validator, round });
                    info!(id, round, validator = %format_validator(&validator), "submitted share generation activation");
                    self.waiters.insert(id, Waiter::Generation(response));
                }
                Message::AbortResharing {
                    validator,
                    round,
                    response,
                } => {
                    let id = self.submit(Command::AbortResharing { validator, round });
                    info!(id, round, validator = %format_validator(&validator), "submitted reshare abort");
                    self.waiters.insert(id, Waiter::Abort(response));
                }
                Message::Reconfigure {
                    change,
                    endorsement,
                    response,
                } => {
                    let (epoch, remove, add) = (
                        change.epoch,
                        hex::encode(change.remove.encode()),
                        hex::encode(change.add.encode()),
                    );
                    let id = self.submit(endorse(Command::Reconfigure(change), endorsement));
                    info!(id, epoch, remove, add, "submitted reconfiguration");
                    let _ = response.send(id);
                }
                Message::ImportHistory {
                    import,
                    endorsement,
                    response,
                } => {
                    let validators = import.validators.len();
                    let id = self.submit(endorse(
                        Command::ImportSlashingProtection(import),
                        endorsement,
                    ));
                    info!(id, validators, "submitted slashing-protection import");
                    self.waiters.insert(id, Waiter::History(response));
                }
                Message::CheckHistory {
                    import,
                    histories,
                    response,
                } => {
                    let _ =
                        response.send(self.store.protection().check_history(&import, &histories));
                }
                Message::ActivateImported {
                    validator,
                    chain,
                    acknowledgment,
                    endorsement,
                    response,
                } => {
                    let id = self.submit(endorse(
                        Command::ActivateImportedValidator {
                            validator,
                            chain,
                            acknowledgment,
                        },
                        endorsement,
                    ));
                    info!(
                        id,
                        validator = %format_validator(&validator),
                        genesis_validators_root = %format_root(&chain.genesis_validators_root),
                        "submitted imported validator activation"
                    );
                    self.waiters.insert(id, Waiter::Activate(response));
                }
                Message::ActivateBatch {
                    batch,
                    endorsement,
                    response,
                } => {
                    let validators = batch.validators.len();
                    let genesis_validators_root = format_root(&batch.chain.genesis_validators_root);
                    let id = self.submit(endorse(Command::ActivateValidators(batch), endorsement));
                    info!(
                        id,
                        validators,
                        %genesis_validators_root,
                        "submitted batch of validator activations"
                    );
                    self.waiters.insert(id, Waiter::ActivateBatch(response));
                }
                Message::ImportStatus { id, response } => {
                    let status = self.store.ceremonies().get(&id).map(|ceremony| {
                        let protection = self.store.protection();
                        let validator = ceremony
                            .public_key()
                            .and_then(|key| key.encode().as_ref().try_into().ok())
                            .and_then(|key: ValidatorKey| protection.validator_of(&key));
                        ImportStatus {
                            ceremony: ceremony.clone(),
                            validator: validator
                                .and_then(|(_, validator)| self.validator_entry(validator)),
                            imported: validator
                                .and_then(|(id, _)| protection.imported(id).copied()),
                        }
                    });
                    let _ = response.send(status);
                }
                Message::Export {
                    validator,
                    response,
                } => {
                    let protection = self.store.protection();
                    let entry =
                        protection
                            .validator_of(&validator)
                            .map(|(id, entry)| ExportEntry {
                                chain: entry.activation.map(|activation| activation.chain).or_else(
                                    || protection.imported(id).and_then(|imported| imported.chain),
                                ),
                                exported: protection.export(id),
                            });
                    let _ = response.send(entry);
                }
                Message::SubmitDuty {
                    request,
                    endorsement,
                    response,
                } => {
                    let validator = format_validator(&request.validator);
                    let kind = request.duty.kind();
                    let signing_root = format_root(&request.signing_root());
                    // A burst of registrations waits in a bounded queue: beyond it, a retryable
                    // refusal (`eth::registration`).
                    if request.duty.registration().is_some()
                        && self.mempool.registrations() >= MAX_PENDING_REGISTRATIONS
                    {
                        warn!(%validator, %signing_root, "builder registration queue full: not submitted");
                        let _ = response.send(Err(Overloaded));
                        continue;
                    }
                    let id = self.submit(endorse(Command::Duty(request), endorsement));
                    info!(id, %validator, ?kind, %signing_root, "submitted validator duty");
                    self.waiters.insert(id, Waiter::Duty(response));
                }
                Message::CheckDuty { request, response } => {
                    let protection = self.store.protection();
                    let (signing_root, decision) = protection.check(&request);
                    let validator = protection
                        .validator_of(&request.validator)
                        .and_then(|(_, validator)| self.validator_entry(validator));
                    let _ = response.send(DutyCheck {
                        validator,
                        signing_root,
                        decision,
                        height: protection.authorized_at(&request),
                        approved: protection.is_approved(&request),
                        policy: request
                            .duty
                            .terms()
                            .and(self.store.registration_policy().cloned()),
                    });
                }
                Message::SetRegistrationPolicy {
                    policy,
                    endorsement,
                    response,
                } => {
                    let digest = format!("0x{}", hex::encode(policy.digest()));
                    let id =
                        self.submit(endorse(Command::SetRegistrationPolicy(policy), endorsement));
                    info!(id, %digest, "submitted builder registration policy");
                    let _ = response.send(id);
                }
                Message::RegistrationPolicy { response } => {
                    let _ = response.send((
                        self.store.registration_policy().cloned(),
                        self.store.height(),
                    ));
                }
                Message::ValidatorRound { round, response } => {
                    let _ = response.send(self.store.protection().is_validator_round(round));
                }
                Message::Validators { response } => {
                    let validators = self
                        .store
                        .protection()
                        .validators()
                        .filter_map(|(_, validator)| self.validator_entry(validator))
                        .collect();
                    let _ = response.send(validators);
                }
                Message::SubmitLog { round, log } => {
                    self.submit(Command::DealerLog { round, log });
                }
                Message::Authorization {
                    ceremony,
                    nonce,
                    response,
                } => {
                    let (ceremony, authorization) = self.store.authorization(&ceremony, nonce);
                    let _ = response.send(Lookup {
                        ceremony: ceremony.cloned(),
                        authorization,
                    });
                }
                Message::Ceremony { id, response } => {
                    let _ = response.send(self.store.ceremonies().get(&id).cloned());
                }
                Message::Status { response } => {
                    let height = self.store.height();
                    let _ = response.send(Status {
                        height,
                        authorizations: self.store.authorization_count(),
                        mempool: self.mempool.len(),
                        admin_nonce: self.store.admin().nonce,
                        progress: Progress {
                            applied: height,
                            known_finalized: self.tip.load(Ordering::Acquire).max(height),
                            last_applied: self.last_applied,
                        },
                        anchor_behind: self.anchor.is_some(),
                    });
                }
                Message::Finalized { block, ack } => {
                    if !held.is_empty() || hooks::hold(!block.transactions.is_empty()) {
                        if held.is_empty() {
                            warn!(
                                height = block.height.get(),
                                "test hook: holding finalized block"
                            );
                        }
                        held.push_back((block, ack));
                        continue;
                    }
                    self.execute(&block).await;
                    ack.acknowledge();
                    // The epoch ended with this block: nothing more is applied.
                    if self.stopped.get().is_some() {
                        return;
                    }
                }
            }
        }
    }

    /// [Executor::reshares], built again once the state has moved on (one walk per block, only
    /// when asked).
    fn reshare_rounds(&self) -> Ref<'_, ReshareRounds> {
        let height = self.store.height();
        if self.reshares.borrow().0 != Some(height) {
            let mut rounds = ReshareRounds::new();
            for ceremony in self.store.ceremonies().iter() {
                if ceremony.status == DkgStatus::Completed
                    && let Some(reshare) = ceremony.reshare()
                {
                    rounds
                        .entry(reshare.validator)
                        .or_default()
                        .push(ceremony.round);
                }
            }
            *self.reshares.borrow_mut() = (Some(height), rounds);
        }
        Ref::map(self.reshares.borrow(), |(_, rounds)| rounds)
    }

    fn validator_entry(&self, validator: &Validator) -> Option<ValidatorEntry> {
        let ceremonies = self.store.ceremonies();
        let ceremony = ceremonies.by_round(validator.round)?;
        let protection = self.store.protection();
        // Every activated reshare of the key up to its active round is one generation.
        let generation = self
            .reshare_rounds()
            .get(&validator.key)
            .map_or(0, |rounds| {
                rounds
                    .iter()
                    .filter(|round| **round <= validator.round)
                    .count()
            }) as u64;
        Some(ValidatorEntry {
            key: validator.key,
            ceremony: ceremony.config.id.clone(),
            round: validator.round,
            activation: validator.activation,
            imported: protection
                .validator_of(&validator.key)
                .is_some_and(|(id, _)| protection.imported(id).is_some()),
            generation,
        })
    }

    /// Add a command to the mempool and gossip it. Returns the transaction id.
    fn submit(&mut self, command: Command) -> u64 {
        let transaction = Transaction {
            id: self.context.next_u64(),
            command,
        };
        let id = transaction.id;
        if !hooks::drop_first_gossip() {
            self.gossip
                .send(Recipients::All, transaction.encode(), false);
        }
        if let Some(unfinalized) = &mut self.unfinalized {
            unfinalized.insert(transaction.digest(), transaction.clone());
        }
        self.mempool.insert(transaction);
        id
    }

    async fn execute(&mut self, block: &Block) {
        let height = block.height.get();
        if height <= self.store.height() {
            // Marshal delivers at-least-once (e.g. again after a restart).
            debug!(height, "block already applied");
            return;
        }
        // Marshal delivers every finalized height in order, resuming after the last one it saw
        // acknowledged. A gap means the replicated state lost blocks marshal already handed over
        // (restored, corrupted or deleted state partition): applying on top would silently diverge
        // from the other nodes, so stop instead.
        let expected = self.store.height() + 1;
        assert!(
            height == expected,
            "replicated state is at height {} but finalized block {height} was delivered: blocks are \
             missing from the state (restored, corrupted or deleted storage?); refusing to continue",
            self.store.height()
        );

        let finalized_at = self.context.current();
        let authorizes = block
            .transactions
            .iter()
            .any(|transaction| matches!(transaction.command, Command::Sign(_) | Command::Duty(_)));
        if authorizes {
            hooks::crash_point("before-apply-authorization");
        }
        let activates = block
            .transactions
            .iter()
            .any(|transaction| matches!(transaction.command, Command::ActivateGeneration { .. }));
        if activates {
            hooks::crash_point("before-apply-activation");
        }
        let reconfigures = crate::epochs::is_terminal(block);
        if reconfigures {
            hooks::crash_point("before-apply-reconfiguration");
        }
        let applied = self
            .store
            .apply_block(
                height,
                &block.digest(),
                &block.transactions,
                &mut *self.context,
            )
            .await
            .expect("failed to persist state");
        // Everything below happens once the block is durably committed.
        let applied_at = self.context.current();
        if authorizes {
            hooks::crash_point("after-apply-authorization");
        }
        if activates {
            hooks::crash_point("after-apply-activation");
        }
        if reconfigures {
            hooks::crash_point("after-apply-reconfiguration");
        }
        if let Some(record) = &applied.reconfigured {
            info!(
                height,
                epoch = record.epoch,
                committee = ?record.committee,
                "the consensus epoch ended with this block: stopping to restart in the next one"
            );
            let _ = self.stopped.set(Stop::Reconfigured {
                epoch: record.epoch,
                height,
            });
        } else if self.close == Some(height) {
            warn!(
                height,
                "the consensus epoch was closed here without a reconfiguration: stopping \
                 (restart without --close-epoch-at)"
            );
            let _ = self.stopped.set(Stop::Closed { height });
        }
        let nonce = self.store.admin().nonce;
        self.committed
            .set(height, nonce, self.store.registration_policy().cloned());
        self.executed.store(height, Ordering::Release);
        self.last_applied = Some(applied_at);
        self.mempool.remove_all(&block.transactions);
        // Protected commands whose nonce is now used never apply: forget them.
        let used = |transaction: &Transaction| matches!(&transaction.command, Command::Admin(authorized) if authorized.nonce <= nonce);
        self.mempool.retain(|transaction| {
            let forget = used(transaction);
            if forget {
                debug!(
                    id = transaction.id,
                    "forgetting a protected command whose nonce is used"
                );
            }
            !forget
        });
        if let Some(unfinalized) = &mut self.unfinalized {
            for transaction in &block.transactions {
                unfinalized.remove(&transaction.digest());
            }
            unfinalized.retain(|_, transaction| !used(transaction));
            if height.is_multiple_of(REGOSSIP_BLOCKS) {
                for transaction in unfinalized.values() {
                    debug!(
                        id = transaction.id,
                        "gossiping an unfinalized transaction again"
                    );
                    self.gossip
                        .send(Recipients::All, transaction.encode(), false);
                }
            }
        }

        // The DKG actor (which holds the shares) learns about committed changes before any client
        // is answered, so a coordinator that just got its receipt finds them there. The purpose of
        // a ceremony comes first.
        if !applied.designated.is_empty() {
            let _ = self
                .dkg
                .send(dkg::actor::Message::ValidatorRounds(applied.designated));
        }
        // Activated share generations, before the ceremonies they retire.
        let moved: std::collections::HashSet<u64> = applied
            .effects
            .iter()
            .filter_map(|effect| match effect {
                Effect::Generation(GenerationOutcome::Activated { from }) => Some(*from),
                _ => None,
            })
            .chain(applied.generations.iter().map(|(_, round)| *round))
            .collect();
        if !applied.generations.is_empty() {
            let _ = self
                .dkg
                .send(dkg::actor::Message::Generations(applied.generations));
        }
        for ceremony in applied.changed {
            match (ceremony.status, ceremony.public_key()) {
                (DkgStatus::Completed, _) if moved.contains(&ceremony.round) => {}
                (DkgStatus::Completed, Some(key)) => info!(
                    height,
                    ceremony = %ceremony.config.id,
                    round = ceremony.round,
                    public_key = %format_key(key),
                    "dkg ceremony completed"
                ),
                (DkgStatus::Failed, _) => warn!(
                    height,
                    ceremony = %ceremony.config.id,
                    round = ceremony.round,
                    logs = ceremony.logs.len(),
                    "dkg ceremony failed: not enough dealer logs before the deadline"
                ),
                _ => {}
            }
            let _ = self.dkg.send(dkg::actor::Message::Ceremony(ceremony));
        }
        if !applied.authorized.is_empty() {
            let _ = self
                .dkg
                .send(dkg::actor::Message::Authorized(applied.authorized));
        }
        // The keyholder checks registrations against the policy in force: before the duties the
        // same block authorized under it.
        if let Some(policy) = applied.registration_policy.clone() {
            let _ = self
                .dkg
                .send(dkg::actor::Message::RegistrationPolicy(Some(policy)));
        }
        if !applied.duties.is_empty() {
            let _ = self
                .dkg
                .send(dkg::actor::Message::AuthorizedDuties(applied.duties));
        }
        let _ = self.dkg.send(dkg::actor::Message::Tick {
            height,
            digest: block.digest(),
        });
        // The anchor's records against this chain: confirmed (the keyholder signs), or rolled back
        // (stop: the network finalizes what it had finalized differently, or below it).
        if let Some(watch) = &mut self.anchor {
            match watch.applied(height, block.digest(), self.tip.load(Ordering::Acquire)) {
                crate::anchor::Verdict::Pending => {}
                crate::anchor::Verdict::Confirmed => {
                    info!(height, "anchor: this chain holds what the records name");
                    let _ = self.dkg.send(dkg::actor::Message::AnchorConfirmed);
                    self.anchor = None;
                }
                crate::anchor::Verdict::RolledBack(why) => {
                    error!(
                        height,
                        %why,
                        "anchor: this network was rolled back behind the anchor: stopping (exit \
                         status 77; docs/anchor.md)"
                    );
                    let _ = self.stopped.set(Stop::RolledBack { height });
                }
            }
        }

        if !block.transactions.is_empty() {
            let accepted = applied
                .effects
                .iter()
                .filter(|effect| {
                    matches!(
                        effect,
                        Effect::Sign(Outcome::Accepted, _) | Effect::Duty(Decision::Accepted, _)
                    )
                })
                .count();
            info!(
                height,
                view = block.view,
                transactions = block.transactions.len(),
                accepted,
                "applied block"
            );
        }

        // A transaction the leaders dropped (beyond the horizon, a registration past its window)
        // never lands: its waiter goes once its client stops waiting.
        self.waiters.retain(|_, waiter| !waiter.is_closed());
        for (transaction, effect) in block.transactions.iter().zip(applied.effects) {
            let waiter = self.waiters.remove(&transaction.id);
            // An approved protected command has the command's own effect.
            let command = match &transaction.command {
                Command::Admin(authorized) => {
                    info!(
                        height,
                        id = transaction.id,
                        nonce = authorized.nonce,
                        approvals = authorized.approvals.len(),
                        "applied an approved protected command"
                    );
                    &authorized.command
                }
                command => command,
            };
            match (command, effect) {
                (Command::Sign(request), Effect::Sign(outcome, authorization)) => {
                    info!(
                        height,
                        id = transaction.id,
                        ceremony = %request.ceremony,
                        nonce = request.nonce,
                        payload_hash = %format_hash(&request.payload_hash),
                        ?outcome,
                        "applied signing authorization"
                    );
                    if let Some(Waiter::Sign(waiter)) = waiter {
                        let _ = waiter.send(Receipt {
                            outcome,
                            height,
                            authorization,
                            finalized_at,
                            applied_at,
                        });
                    }
                }
                (
                    Command::StartCeremony(config) | Command::StartValidatorCeremony(config),
                    Effect::Start(outcome),
                ) => {
                    info!(height, id = transaction.id, ceremony = %config.id, ?outcome, "applied ceremony start");
                    if let Some(Waiter::Start(waiter)) = waiter {
                        let _ = waiter.send(StartReceipt { outcome, height });
                    }
                }
                (Command::Duty(request), Effect::Duty(decision, signing_root)) => {
                    info!(
                        height,
                        id = transaction.id,
                        validator = %format_validator(&request.validator),
                        kind = ?request.duty.kind(),
                        signing_root = %format_root(&signing_root),
                        ?decision,
                        "applied validator duty"
                    );
                    if let Some(Waiter::Duty(waiter)) = waiter {
                        let _ = waiter.send(Ok(DutyReceipt {
                            decision,
                            signing_root,
                            height,
                            authorized_at: self.store.protection().authorized_at(request),
                            finalized_at,
                            applied_at,
                        }));
                    }
                }
                (Command::ActivateValidator { validator, chain }, Effect::Activate(outcome)) => {
                    info!(
                        height,
                        id = transaction.id,
                        validator = %format_validator(validator),
                        genesis_validators_root = %format_root(&chain.genesis_validators_root),
                        ?outcome,
                        "applied validator activation"
                    );
                    if let Some(Waiter::Activate(waiter)) = waiter {
                        let _ = waiter.send(ActivationReceipt { outcome, height });
                    }
                }
                (Command::DealerLog { round, .. }, Effect::Log(outcome)) => match outcome {
                    Ok(dealer) => info!(height, round, ?dealer, "recorded dealer log"),
                    Err(reason) => debug!(height, round, %reason, "ignored dealer log"),
                },
                (Command::RegisterImportedKey(manifest), Effect::Register(outcome)) => {
                    info!(
                        height,
                        id = transaction.id,
                        ceremony = %manifest.ceremony,
                        validator = %format_validator(&manifest.validator),
                        ?outcome,
                        "applied imported key registration"
                    );
                    if let Some(Waiter::Register(waiter)) = waiter {
                        let _ = waiter.send(RegisterReceipt { outcome, height });
                    }
                }
                (Command::RegisterImportedKeys(batch), Effect::RegisterBatch(outcome)) => {
                    info!(
                        height,
                        id = transaction.id,
                        keys = batch.manifests.len(),
                        ?outcome,
                        "applied batch of imported key registrations"
                    );
                    if let Some(Waiter::RegisterBatch(waiter)) = waiter {
                        let _ = waiter.send(BatchRegisterReceipt { outcome, height });
                    }
                }
                (Command::ShareReady(ack), Effect::Ready(outcome)) => match outcome {
                    Ok(index) => info!(
                        height,
                        round = ack.round,
                        index,
                        "recorded share acknowledgement"
                    ),
                    Err(reason) => {
                        warn!(height, round = ack.round, %reason, "ignored share acknowledgement")
                    }
                },
                (
                    Command::StartResharing {
                        validator,
                        ceremony,
                        ..
                    },
                    Effect::Reshare(outcome),
                ) => {
                    info!(
                        height,
                        id = transaction.id,
                        %ceremony,
                        validator = %format_validator(validator),
                        ?outcome,
                        "applied reshare start"
                    );
                    if let Some(Waiter::Reshare(waiter)) = waiter {
                        let _ = waiter.send(ReshareReceipt { outcome, height });
                    }
                }
                (Command::ActivateGeneration { validator, round }, Effect::Generation(outcome)) => {
                    info!(
                        height,
                        id = transaction.id,
                        round,
                        validator = %format_validator(validator),
                        ?outcome,
                        "applied share generation activation"
                    );
                    if let Some(Waiter::Generation(waiter)) = waiter {
                        let _ = waiter.send(GenerationReceipt { outcome, height });
                    }
                }
                (Command::AbortResharing { validator, round }, Effect::Abort(outcome)) => {
                    info!(
                        height,
                        id = transaction.id,
                        round,
                        validator = %format_validator(validator),
                        ?outcome,
                        "applied reshare abort"
                    );
                    if let Some(Waiter::Abort(waiter)) = waiter {
                        let _ = waiter.send(AbortReceipt { outcome, height });
                    }
                }
                (Command::ImportSlashingProtection(import), Effect::History(outcome)) => {
                    info!(
                        height,
                        id = transaction.id,
                        validators = import.validators.len(),
                        digest = %format_root(&import.digest),
                        ?outcome,
                        "applied slashing-protection import"
                    );
                    if let Some(Waiter::History(waiter)) = waiter {
                        let _ = waiter.send(HistoryReceipt { outcome, height });
                    }
                }
                (
                    Command::ActivateImportedValidator {
                        validator, chain, ..
                    },
                    Effect::Activate(outcome),
                ) => {
                    info!(
                        height,
                        id = transaction.id,
                        validator = %format_validator(validator),
                        genesis_validators_root = %format_root(&chain.genesis_validators_root),
                        ?outcome,
                        "applied imported validator activation"
                    );
                    if let Some(Waiter::Activate(waiter)) = waiter {
                        let _ = waiter.send(ActivationReceipt { outcome, height });
                    }
                }
                (Command::ActivateValidators(batch), Effect::ActivateBatch(outcome)) => {
                    info!(
                        height,
                        id = transaction.id,
                        validators = batch.validators.len(),
                        genesis_validators_root = %format_root(&batch.chain.genesis_validators_root),
                        ?outcome,
                        "applied batch of validator activations"
                    );
                    if let Some(Waiter::ActivateBatch(waiter)) = waiter {
                        let _ = waiter.send(BatchActivationReceipt { outcome, height });
                    }
                }
                (Command::SetRegistrationPolicy(policy), Effect::RegistrationPolicy(digest)) => {
                    info!(
                        height,
                        id = transaction.id,
                        digest = %format!("0x{}", hex::encode(digest)),
                        fee_recipients = policy.fee_recipients.len(),
                        gas_limit_min = policy.gas_limit_min,
                        gas_limit_max = policy.gas_limit_max,
                        max_future_seconds = policy.max_future_seconds,
                        max_age_seconds = policy.max_age_seconds,
                        "applied builder registration policy"
                    );
                }
                // Nobody waits: the node stops right after this block (`Stop`).
                (Command::Reconfigure { .. }, Effect::Reconfigure(record)) => info!(
                    height,
                    id = transaction.id,
                    epoch = record.epoch,
                    "applied reconfiguration"
                ),
                _ => unreachable!("one effect per command"),
            }
        }

        // The archives only drop whole sections, so prune once per section rather than per block.
        let retained = self.retention.blocks.get();
        if height.is_multiple_of(self.retention.section.get()) && height > retained {
            let below = height - retained;
            info!(height, below, "pruning finalized history");
            self.marshal.prune(Height::new(below));
        }
    }
}

/// Add transactions gossiped by peers to the local mempool.
pub async fn receive_gossip(mut receiver: impl Receiver<PublicKey = PublicKey>, mempool: Mempool) {
    while let Ok((peer, message)) = receiver.recv().await {
        match Transaction::decode(message) {
            Ok(transaction) => {
                mempool.insert_from(Some(peer), transaction);
            }
            Err(err) => warn!(?peer, ?err, "invalid mempool message"),
        }
    }
}
