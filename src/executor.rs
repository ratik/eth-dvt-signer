/// How often a held-back block is checked again (test hook only).
const HOLD_POLL: Duration = Duration::from_millis(50);

/// A follower never proposes, so a transaction it submitted reaches a block only through its
/// gossip: it gossips each one again every this many applied blocks until a block contains it.
const REGOSSIP_BLOCKS: u64 = 4;

/// Final answer for a submitted signing authorization, sent once its block is durably applied.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Receipt {
    pub outcome: Outcome,
    /// Height of the block that finalized the request.
    pub height: u64,
    /// The authorization of `(ceremony, nonce)` after the request (the earlier one if it was
    /// already decided).
    pub authorization: Option<Authorization>,
    /// When this node started applying the block.
    pub finalized_at: SystemTime,
    /// When the block was durably applied.
    pub applied_at: SystemTime,
}

/// Final answer for a submitted validator duty, sent once its block is durably applied.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DutyReceipt {
    pub decision: Decision,
    /// The signing root the state machine computed for the duty.
    pub signing_root: Root,
    /// Height of the block that decided the duty.
    pub height: u64,
    /// Height of the block that authorized this signing root, if it is authorized: this block for
    /// a new authorization, the original one for a retry (`AlreadyAccepted`).
    pub authorized_at: Option<u64>,
    pub finalized_at: SystemTime,
    pub applied_at: SystemTime,
}

/// A validator key: its public key, the ceremony that signs for it, and its activation (none:
/// it signs nothing yet).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ValidatorEntry {
    pub key: ValidatorKey,
    /// The ceremony of its active share generation.
    pub ceremony: CeremonyId,
    pub round: u64,
    pub activation: Option<Activation>,
    /// Imported from another signer (`import`), not generated by the DKG.
    pub imported: bool,
    /// Share generations activated since the key's first (0: never reshared).
    pub generation: u64,
}

